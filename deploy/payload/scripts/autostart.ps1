# MemoFirst：開機自動啟動（在「所有使用者」開機啟動資料夾建立 VBS，登入後以本人身分背景啟動）
# 不用排程工作、不占 SYSTEM 身分；設定後日常 start.bat / stop.bat 直接雙擊即可，不需系統管理員。
param([Parameter(Mandatory = $true)][ValidateSet("on", "off")][string]$Mode)
$ErrorActionPreference = "Continue"
$Root = Split-Path -Parent $PSScriptRoot
$Name = "MemoFirst"       # VBS 檔名（與舊版同名排程共用此識別字，供遷移清除）

# 寫入「所有使用者」開機啟動資料夾需系統管理員；用固定機器路徑而非個人資料夾，
# 避免提權後 GetFolderPath 抓到管理者設定檔、VBS 落錯位置而靜默失效。
$identity = [Security.Principal.WindowsIdentity]::GetCurrent()
$isAdmin = ([Security.Principal.WindowsPrincipal]$identity).IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $isAdmin) {
  Write-Host "[錯誤] 需要系統管理員權限，請改用 autostart-on.bat 或 autostart-off.bat（會自動要求權限）。" -ForegroundColor Red
  exit 1
}

$startupDir = [Environment]::GetFolderPath("CommonStartup")
$vbsPath = Join-Path $startupDir ($Name + ".vbs")
$startPs1 = Join-Path $Root "scripts\start.ps1"

if ($Mode -eq "on") {
  # VBS 以 WScript.Shell.Run 隱藏視窗（第 2 引數 0）背景執行 start.ps1，登入時不閃主控台。
  # 內層連續兩個雙引號是 VBS 字串的跳脫引號，用來包住含空白的路徑。
  $vbs = @"
' Boot auto-start for $Name. Generated by autostart.ps1 - do not edit by hand.
' Launches the server hidden at user logon (no scheduled task, no SYSTEM account).
CreateObject("WScript.Shell").Run "powershell.exe -NoProfile -ExecutionPolicy Bypass -File ""$startPs1""", 0, False
"@
  # 以 UTF-16 LE + BOM 寫入，WScript 依 BOM 判讀 Unicode，安裝路徑含中文也不會壞。
  [IO.File]::WriteAllText($vbsPath, $vbs, [Text.Encoding]::Unicode)
  & schtasks.exe /Delete /F /TN $Name 2>$null | Out-Null
  if (Test-Path $vbsPath) {
    Write-Host "已設定開機自動啟動：登入這台電腦後會自動在背景啟動伺服器。" -ForegroundColor Green
    Write-Host "  啟動項：$vbsPath" -ForegroundColor Green
    Write-Host "  伺服器以你的帳號執行，日後 start.bat、stop.bat 直接雙擊即可，不需系統管理員。" -ForegroundColor Yellow
  } else {
    Write-Host "[錯誤] 開機啟動項建立失敗（$vbsPath）。" -ForegroundColor Red
    exit 1
  }
} else {
  $removed = Test-Path $vbsPath
  if ($removed) { Remove-Item $vbsPath -Force -ErrorAction SilentlyContinue }
  & schtasks.exe /Delete /F /TN $Name 2>$null | Out-Null
  if ($removed) {
    Write-Host "已移除開機自動啟動（刪除 $vbsPath）。" -ForegroundColor Green
  } else {
    Write-Host "沒有找到開機自動啟動項（可能本來就未設定）。" -ForegroundColor Yellow
  }
}
