import path from 'path';
import fs from 'fs';

// ---------------------------------------------------------------------------
// Runtime configuration — Tailscale passwordless hosting model.
//
// The app listens on 127.0.0.1 only; `tailscale serve` reverse-proxies the
// tailnet and injects the `Tailscale-User-Login` header as the identity.
// ---------------------------------------------------------------------------

/** Listen port. serve 對外埠 = app 埠 = URL 埠（同一個數字）。 */
export const PORT = parseInt(process.env.PORT ?? '28470', 10);

/**
 * Bind address. MUST stay 127.0.0.1 — binding 0.0.0.0 would let anyone on the
 * LAN connect directly and forge the Tailscale-User-Login header (信任模型鐵則 1)。
 */
export const HOST = process.env.HOST ?? '127.0.0.1';

/** Admin email allowlist (comma-separated, matched case-insensitively). */
export const ADMIN_LOGINS: Set<string> = new Set(
  (process.env.ADMIN_LOGINS ?? '')
    .split(',')
    .map((s) => s.trim().toLowerCase())
    .filter(Boolean),
);

/**
 * Dev-only identity override used when running without `tailscale serve`
 * (no injected header) on a non-loopback bind. MUST be empty in production
 * (信任模型鐵則 4)。
 */
export const DEV_BYPASS_LOGIN = (process.env.DEV_BYPASS_LOGIN ?? '').trim().toLowerCase();

// Project root — where 網址.txt is generated by serve-setup.
const APP_ROOT = path.join(__dirname, '..', '..');

/**
 * Public Tailscale URL shown to colleagues. serve-setup writes it to 網址.txt;
 * read lazily so a freshly-generated file is picked up without a restart.
 */
export function getPublicUrl(): string | null {
  if (process.env.PUBLIC_URL) return process.env.PUBLIC_URL.trim();
  try {
    const p = path.join(APP_ROOT, '網址.txt');
    if (fs.existsSync(p)) {
      const url = fs.readFileSync(p, 'utf8').trim();
      return url || null;
    }
  } catch {
    // ignore — fall back to null
  }
  return null;
}

// ---------------------------------------------------------------------------
// Join-password validation — shared by meeting create / unlock.
// ---------------------------------------------------------------------------
export function validateJoinPassword(
  password: unknown,
): { valid: boolean; error?: string } {
  if (typeof password !== 'string' || password.length < 4) {
    return { valid: false, error: '加入密碼至少 4 個字元' };
  }
  return { valid: true };
}
